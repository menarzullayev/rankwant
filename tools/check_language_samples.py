#!/usr/bin/env python3
"""The `/about` language samples are the judge-verified A+B sources, unchanged.

`apps/web/src/content/about/language-samples.ts` is generated by
`tools/render_language_samples.py` from `tools/aplus_solutions.py` and
`tools/aplus_file_solutions.py`, the sources `tools/submit_aplus_matrix.py`
sends to the live judge. Two things went wrong before this check existed
(found 2026-11-14):

  * the sources were corrected and the page was not generated again: five
    samples on the page were not the verified ones;
  * the generator wrote the code into template literals without escaping it,
    so every sample with a backslash was shown wrong (`/\\s+/` as `/s+/`).

    check_language_samples.py              the file is what the generator writes
    check_language_samples.py --selftest   the escaping and this comparison work

Exit 0: in step. Exit 1: out of step (run the generator). Exit 2: cannot tell.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _console  # noqa: E402

_console.force_utf8()

import render_language_samples as renderer  # noqa: E402

BACKSLASH = "\\"


def evaluated(body: str) -> str:
    """What a template literal with this body evaluates to, for the escapes the
    generator writes (`\\\\`, `` \\` ``, `\\$`). Anything else after a backslash
    means the body was not written by `template_literal`."""
    out: list[str] = []
    i = 0
    while i < len(body):
        char = body[i]
        if char == BACKSLASH:
            if i + 1 >= len(body) or body[i + 1] not in (BACKSLASH, "`", "$"):
                raise ValueError(f"unexpected escape at {i}: {body[i : i + 2]!r}")
            out.append(body[i + 1])
            i += 2
            continue
        if char == "`" or body.startswith("${", i):
            raise ValueError(f"unescaped {body[i : i + 2]!r} at {i}")
        out.append(char)
        i += 1
    return "".join(out)


def out_of_step(committed: str, expected: str) -> list[str]:
    """Why `committed` is not `expected`; empty when it is. Line ends do not count."""
    committed = committed.replace("\r\n", "\n")
    if committed == expected:
        return []
    old, new = committed.split("\n"), expected.split("\n")
    for number, (a, b) in enumerate(zip(old, new), start=1):
        if a != b:
            return [f"line {number}: has {a[:80]!r}, the sources give {b[:80]!r}"]
    return [f"{len(old)} lines, the sources give {len(new)}"]


def check() -> int:
    if not renderer.OUT.is_file():
        print(f"language samples: {renderer.OUT} is missing")
        return 2
    problems = out_of_step(renderer.OUT.read_text(encoding="utf-8"), renderer.render())
    if problems:
        print(
            "language samples: apps/web/src/content/about/language-samples.ts is out of step"
        )
        for problem in problems:
            print(f"  - {problem}")
        print("  run: python tools/render_language_samples.py")
        return 1
    count = len(renderer.APLUS) + len(renderer.APLUS_FILE)
    print(f"language samples: {count} samples are the verified sources")
    return 0


#: Code that a raw template literal would change. Each must come back as written.
ROUND_TRIP = [
    "const d = s.split(/\\s+/);",
    'echo $a + $b, "\\n";',
    "print('${a + b}');",
    "let s = `${a}`;",
    "a \\` b \\${ c \\\\ d",
    "format('~w~n', [S]).",
    "plain text, nothing special",
    "ends with a backslash \\",
    "$ { is not an interpolation, ${ is",
]


def selftest() -> int:
    failures: list[str] = []
    for text in ROUND_TRIP:
        body = renderer.template_literal(text)
        try:
            back = evaluated(body)
        except ValueError as exc:
            failures.append(f"{text!r}: {exc}")
            continue
        if back != text:
            failures.append(f"{text!r} came back as {back!r}")

    # The escaping must be what protects: the same text written raw is refused.
    for raw in ("split(/\\s+/)", "print('${a}')", "a ` b"):
        try:
            evaluated(raw)
        except ValueError:
            continue
        failures.append(f"raw {raw!r} was accepted as a template literal body")

    # Every real sample survives the round trip.
    for name, samples in (("stdio", renderer.APLUS), ("file", renderer.APLUS_FILE)):
        for code, text in samples.items():
            if evaluated(renderer.template_literal(text)) != text:
                failures.append(f"{name}/{code} does not survive the template literal")

    expected = renderer.render()
    if out_of_step(expected, expected):
        failures.append("the generator's own output is reported out of step")
    if out_of_step(expected.replace("\n", "\r\n"), expected):
        failures.append("CRLF line ends are reported as a difference")
    drifted = expected.replace("long long a, b;", "long long a;", 1)
    if drifted == expected or not out_of_step(drifted, expected):
        failures.append("a changed sample is not reported")
    if not out_of_step(expected + "// extra\n", expected):
        failures.append("an added line is not reported")

    if failures:
        print("language samples self-test FAILED:")
        for failure in failures:
            print(f"  - {failure}")
        return 1
    print(
        f"language samples self-test ok: {len(ROUND_TRIP)} round trips, 3 refusals, 4 comparisons"
    )
    return 0


def main(argv: list[str]) -> int:
    if argv == ["--selftest"]:
        return selftest()
    if argv:
        print("usage: check_language_samples.py [--selftest]")
        return 2
    return check()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
